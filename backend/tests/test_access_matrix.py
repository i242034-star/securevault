"""
Access Matrix Test:
Verifies Alice, Bob, Charlie, and David against the core semester project policy:
Policy: (Role:Engineer OR Role:Manager) AND Clearance:Level-3
"""
import unittest
import sys
import os

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), '..')))

from crypto.charm_engine import CharmEngine


class TestAccessMatrix(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.engine = CharmEngine(curve="BN254")
        cls.pk, cls.mk = cls.engine.setup()

        # Target Core Project Policy
        cls.policy_str = "(Role:Engineer OR Role:Manager) AND Clearance:Level-3"

        # Generate cryptographic secret and ciphertext
        cls.secret_m = cls.engine.random_message()
        cls.ct, cls.formatted_policy = cls.engine.encrypt(cls.pk, cls.secret_m, cls.policy_str)

    def test_alice_access_granted(self):
        """Alice: Role:Engineer, Clearance:Level-3 -> Expected: SUCCESS"""
        alice_attrs = ["Role:Engineer", "Clearance:Level-3"]
        sk_alice = self.engine.keygen(self.pk, self.mk, alice_attrs)
        recovered = self.engine.decrypt(self.pk, sk_alice, self.ct)
        self.assertEqual(recovered, self.secret_m, "Alice must successfully decrypt the ciphertext.")

    def test_charlie_access_granted(self):
        """Charlie: Role:Manager, Clearance:Level-3 -> Expected: SUCCESS"""
        charlie_attrs = ["Role:Manager", "Clearance:Level-3"]
        sk_charlie = self.engine.keygen(self.pk, self.mk, charlie_attrs)
        recovered = self.engine.decrypt(self.pk, sk_charlie, self.ct)
        self.assertEqual(recovered, self.secret_m, "Charlie must successfully decrypt the ciphertext.")

    def test_bob_access_denied_role_mismatch(self):
        """Bob: Role:Student, Clearance:Level-3 -> Expected: DENIED (Student not authorized)"""
        bob_attrs = ["Role:Student", "Clearance:Level-3"]
        sk_bob = self.engine.keygen(self.pk, self.mk, bob_attrs)
        recovered = self.engine.decrypt(self.pk, sk_bob, self.ct)
        self.assertIsNone(recovered, "Bob must be denied: CP-ABE pairing evaluation must return None.")

    def test_david_access_denied_clearance_mismatch(self):
        """David: Role:Engineer, Clearance:Level-2 -> Expected: DENIED (Insufficient clearance)"""
        david_attrs = ["Role:Engineer", "Clearance:Level-2"]
        sk_david = self.engine.keygen(self.pk, self.mk, david_attrs)
        recovered = self.engine.decrypt(self.pk, sk_david, self.ct)
        self.assertIsNone(recovered, "David must be denied: CP-ABE pairing evaluation must return None.")

    def test_dynamic_attribute_change_david_promotion(self):
        """
        Attribute Change Demonstration:
        David is promoted from Level-2 to Level-3.
        A new key reflecting the updated attributes is generated by the authority.
        David's new key must now successfully decrypt.
        """
        # Old key fails
        sk_david_old = self.engine.keygen(self.pk, self.mk, ["Role:Engineer", "Clearance:Level-2"])
        self.assertIsNone(self.engine.decrypt(self.pk, sk_david_old, self.ct))

        # Admin updates David's clearance to Level-3; Trusted Authority issues new key
        sk_david_new = self.engine.keygen(self.pk, self.mk, ["Role:Engineer", "Clearance:Level-3"])
        recovered = self.engine.decrypt(self.pk, sk_david_new, self.ct)
        self.assertEqual(recovered, self.secret_m, "David's re-issued key must grant decryption access.")


if __name__ == '__main__':
    unittest.main(verbosity=2)
